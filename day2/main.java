package day2;

public class main {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;

        System.out.println("Addition: " + (a + b));
        System.out.println("Remainder: " + (a % b));
        System.out.println("Is a greater than b? " + (a > b));
        System.out.println("Both are positive? " + (a > 0 && b > 0));
    }
}